#!/usr/bin/env python3
"""Regenerate syscalls.go from golang.org/x/sys: python3 tools/gensyscalls.py | gofmt > syscalls.go"""
import re, subprocess, sys

mod = subprocess.check_output(["go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/sys"], text=True).strip()
arches = ["amd64", "arm64"]
table = {}
for i, arch in enumerate(arches):
    for name, nr in re.findall(r"^\s*SYS_(\w+)\s*=\s*(\d+)", open(f"{mod}/unix/zsysnum_linux_{arch}.go").read(), re.M):
        table.setdefault(name.lower(), [-1] * len(arches))[i] = int(nr)

print("// Code generated by tools/gensyscalls.py; DO NOT EDIT.\n\npackage main\n")
print("// syscallTable maps a syscall name to its number on amd64 and arm64 (-1: absent).")
print("var syscallTable = map[string][2]int{")
for name in sorted(table):
    print(f'\t"{name}": {{{table[name][0]}, {table[name][1]}}},')
print("}")
